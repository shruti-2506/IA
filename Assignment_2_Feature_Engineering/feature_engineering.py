import plotly.graph_objects as go

flow = pd.crosstab(
    books_df["price_band"],
    books_df["rating_category"]
).stack().reset_index(name="count")

flow = flow[flow["count"] > 0]

price_labels = sorted(flow["price_band"].astype(str).unique())
rating_labels = sorted(flow["rating_category"].astype(str).unique())

labels = price_labels + rating_labels
label_index = {label: i for i, label in enumerate(labels)}

source = [
    label_index[str(p)] for p in flow["price_band"]
]
target = [
    label_index[str(r)] for r in flow["rating_category"]
]

fig = go.Figure(data=[go.Sankey(
    node=dict(
        label=labels,
        pad=15,
        thickness=20
    ),
    link=dict(
        source=source,
        target=target,
        value=flow["count"].tolist()
    )
)])

fig.update_layout(
    title="Sankey Diagram: Price Category to Rating Category"
)

fig.show()

