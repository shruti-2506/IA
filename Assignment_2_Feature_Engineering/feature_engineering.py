import sys
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Helper for environments without IPython display
try:
    display
except NameError:
    def display(x):
        print(x)

# Load dataset: support both Google Colab and local execution
file_name = None
try:
    from google.colab import files
    uploaded = files.upload()
    if uploaded:
        file_name = next(iter(uploaded))
except (ImportError, ModuleNotFoundError):
    pass

if not file_name:
    csv_candidates = [
        "book_feature_dataset.csv",
        "book_feature_dataset (3).csv",
        "books_feature_dataset.csv"
    ]
    if len(sys.argv) > 1 and os.path.exists(sys.argv[1]):
        file_name = sys.argv[1]
    else:
        for c in csv_candidates:
            if os.path.exists(c):
                file_name = c
                break

if not file_name:
    print("Note: Running without preloaded CSV. Usage: python feature_engineering.py <path_to_csv>")
    sys.exit(0)

df = pd.read_csv(file_name)

print("Dataset loaded successfully!")
print("Original dataset shape:", df.shape)
display(df.head())

books = []

for _, row in df.iterrows():
    for i in range(1, 6):

        books.append({
            "price": row[f"price_{i}"],
            "rating": row[f"rating_{i}"],
            "availability": row[f"availability_{i}"],
            "book_link": row[f"book_link_{i}"]
        })

books_df = pd.DataFrame(books)

print("Dataset reshaped successfully!")
print("Rows and columns:", books_df.shape)
display(books_df.head(10))

# Remove currency symbol and convert price to numeric
books_df["price"] = (
    books_df["price"]
    .astype(str)
    .str.replace("£", "", regex=False)
    .str.strip()
)

books_df["price"] = pd.to_numeric(
    books_df["price"], errors="coerce"
)

# Convert star ratings into numbers
rating_map = {
    "One": 1,
    "Two": 2,
    "Three": 3,
    "Four": 4,
    "Five": 5
}

books_df["rating"] = books_df["rating"].apply(
    lambda x: next(
        (value for word, value in rating_map.items()
         if word in str(x)),
        np.nan
    )
)

# Remove rows with missing essential values
books_df = books_df.dropna(
    subset=["price", "rating", "book_link"]
)

# Remove duplicate books, if any
books_df = books_df.drop_duplicates(
    subset=["book_link"]
).reset_index(drop=True)

print("Data cleaning completed!")
print("Final shape:", books_df.shape)
print("\nMissing values:")
print(books_df.isnull().sum())
print("\nData types:")
print(books_df.dtypes)

display(books_df.head(10))

# Create price categories
books_df["price_band"] = pd.cut(
    books_df["price"],
    bins=[0, 20, 40, np.inf],
    labels=["Budget", "Mid", "Premium"],
    include_lowest=True
)

# Create rating categories
books_df["rating_category"] = pd.cut(
    books_df["rating"],
    bins=[0, 2, 3, 5],
    labels=["Low", "Medium", "High"],
    include_lowest=True
)

print("New features created successfully!")

display(
    books_df[
        ["price", "price_band", "rating",
         "rating_category", "availability"]
    ].head(10)
)

# Encode price categories
price_map = {
    "Budget": 1,
    "Mid": 2,
    "Premium": 3
}

books_df["price_enc"] = (
    books_df["price_band"]
    .astype(str)
    .map(price_map)
)

# Encode rating categories
rating_category_map = {
    "Low": 1,
    "Medium": 2,
    "High": 3
}

books_df["rating_category_enc"] = (
    books_df["rating_category"]
    .astype(str)
    .map(rating_category_map)
)

# Encode availability
availability_map = {
    "Out of stock": 0,
    "In stock": 1
}

books_df["availability_enc"] = (
    books_df["availability"]
    .str.strip()
    .map(availability_map)
)

print("Label encoding completed!")

display(
    books_df[
        ["price_band", "price_enc",
         "rating_category", "rating_category_enc",
         "availability", "availability_enc"]
    ].head(10)
)

price_one_hot = pd.get_dummies(
    books_df["price_band"],
    prefix="price",
    dtype=int
)

rating_one_hot = pd.get_dummies(
    books_df["rating_category"],
    prefix="rating",
    dtype=int
)

print("One-hot encoded price categories:")
display(price_one_hot.head(10))

print("One-hot encoded rating categories:")
display(rating_one_hot.head(10))

books_encoded = pd.concat(
    [books_df, price_one_hot, rating_one_hot],
    axis=1
)

print("Final dataset shape:", books_encoded.shape)
display(books_encoded.head(10))

books_encoded.to_csv(
    "books_feature_engineered.csv",
    index=False
)

print("Feature-engineered dataset saved successfully!")

